"""Daily Loss Tracker — correct daily loss accounting.

Handles:
- Reset at configured trading-day boundary (local midnight of tz_name)
- Survives process restart
- Derives baseline from authoritative broker state
- Handles timezone explicitly
- Detects corrupted/missing baseline
- Fail closed when baseline cannot be trusted

Definition of "trading day":
  A trading day starts at 00:00 in the configured timezone (tz_name,
  default UTC) and ends one second before the next local midnight.
  Daily loss is measured from the equity at the start of the trading day.

Timezone semantics (P1-009):
  The tz_name parameter selects an IANA timezone that determines the
  midnight rollover boundary. Examples:
    tz_name="UTC"              → daily reset at midnight UTC (default)
    tz_name="America/New_York" → daily reset at local midnight New York
    tz_name="Asia/Singapore"   → daily reset at local midnight Singapore

  The broker (Exness) operates in GMT/UTC. The MT5 terminal uses UTC for
  all timestamps. This tracker defaults to UTC to match the broker's
  trading day boundary.

  If your local timezone differs, set tz_name to your IANA zone. The
  rollover follows that zone's local calendar date, so DST transitions
  are handled automatically (e.g. America/New_York resets at 05:00 UTC
  during EST but 04:00 UTC during EDT). Do NOT use a fixed UTC offset:
  it drifts by an hour across DST transitions (C-5).
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any, Dict
from zoneinfo import ZoneInfo

from eigencapital.core.state_schema import (
    SchemaDefinition,
    SchemaError,
    read_versioned,
    write_versioned,
)


def _migrate_daily_baseline(legacy: dict) -> dict:
    """Migrate a legacy daily-baseline payload to schema v1.

    Preserves all original fields (no data loss) and adds the current
    schema version. The baseline hash is not regenerated by migration;
    callers re-verify after migration.
    """
    data = dict(legacy)
    data["schema_version"] = 1
    return data


# Schema for daily_baseline.json. Version 1 adds ``schema_version``; legacy
# (unversioned) files are migrated by preserving all original fields
# (no data loss). The baseline hash is not regenerated by migration;
# callers re-verify after migration.
BASELINE_SCHEMA = SchemaDefinition(
    name="daily_baseline.json",
    version=1,
    required_fields={"date_str", "equity", "timestamp_utc"},
    optional_fields={"hash"},
    migrator=_migrate_daily_baseline,
)


@dataclass(frozen=True)
class DailyBaseline:
    """Immutable record of the daily baseline."""

    date_str: str  # "YYYY-MM-DD"
    equity: float
    timestamp_utc: str
    hash: str = ""

    def compute_hash(self) -> str:
        data = {
            "date_str": self.date_str,
            "equity": self.equity,
            "timestamp_utc": self.timestamp_utc,
        }
        payload = json.dumps(data, sort_keys=True).encode("utf-8")
        return hashlib.sha256(payload).hexdigest()


class DailyLossTracker:
    """Track daily loss with correct midnight reset.

    Usage:
        tracker = DailyLossTracker(persistence_dir="reports/r4_loop")
        tracker.initialize(broker_equity=5010.94)

        # Each cycle:
        tracker.update(equity=4950.0)
        if tracker.is_daily_loss_breached():
            # Halt trading

    The tracker:
    1. Loads existing baseline from disk if available
    2. If no baseline or different day → creates new baseline from current equity
    3. Persists baseline to disk after creation
    4. Computes daily loss as baseline_equity - current_equity
    5. Resets automatically at local midnight in tz_name (DST-aware)
    """

    def __init__(
        self,
        max_daily_loss: float = 250.0,
        persistence_dir: str = "reports/r4_loop",
        tz_name: str = "UTC",
    ) -> None:
        self._max_daily_loss = max_daily_loss
        self._persistence_dir = Path(persistence_dir)
        self._tz_name = tz_name
        self._baseline: DailyBaseline | None = None
        self._current_equity: float = 0.0
        self._baseline_file = self._persistence_dir / "daily_baseline.json"
        # Fail-closed flag (P1 restart-consistency): set when a baseline file
        # exists but cannot be trusted (corrupt JSON, missing fields, hash
        # mismatch). While set, the tracker never silently re-baselines from
        # current equity — that would silently disable the daily-loss limit
        # for the rest of the trading day. Only force_reset() clears it.
        self._corrupted = False

    def _today_str(self) -> str:
        """Get today's date string in the configured timezone."""
        now = datetime.now(tz=ZoneInfo(self._tz_name))
        return now.strftime("%Y-%m-%d")

    def _now_utc(self) -> str:
        return datetime.now(UTC).isoformat()

    def _load_baseline(self) -> DailyBaseline | None:
        """Load baseline from disk using the versioned schema reader.

        Returns ``None`` if the file is missing, unreadable, malformed, or
        fails validation (hash mismatch or unknown schema version). A
        ``SchemaError`` from an unknown version is treated as corrupted
        (fail-closed) rather than silently interpreted.
        """
        if not self._baseline_file.exists():
            return None
        try:
            result = read_versioned(self._baseline_file, BASELINE_SCHEMA)
        except SchemaError:
            # Unknown schema version or validation failure: treat as
            # corrupted — fail closed, never silently interpret.
            return None
        if result is None:
            return None
        data, _version = result
        try:
            baseline = DailyBaseline(
                date_str=data["date_str"],
                equity=data["equity"],
                timestamp_utc=data["timestamp_utc"],
                hash=data.get("hash", ""),
            )
        except (KeyError, TypeError):
            return None  # Missing required fields
        # Verify hash
        expected_hash = baseline.compute_hash()
        if baseline.hash and baseline.hash != expected_hash:
            return None  # Corrupted — treat as missing
        return baseline

    def _save_baseline(self, baseline: DailyBaseline) -> None:
        """Persist baseline to disk atomically with schema version."""
        self._persistence_dir.mkdir(parents=True, exist_ok=True)
        data = {
            "date_str": baseline.date_str,
            "equity": baseline.equity,
            "timestamp_utc": baseline.timestamp_utc,
            "hash": baseline.compute_hash(),
        }
        # Atomic write with schema version (temp file + os.replace)
        write_versioned(self._baseline_file, data, BASELINE_SCHEMA)

    def _make_baseline(self, date_str: str, equity: float) -> DailyBaseline:
        """Create a baseline with pre-computed hash."""
        baseline = DailyBaseline(
            date_str=date_str,
            equity=equity,
            timestamp_utc=self._now_utc(),
        )
        # Compute hash with empty string, then create final with hash
        h = baseline.compute_hash()
        return DailyBaseline(
            date_str=date_str,
            equity=equity,
            timestamp_utc=baseline.timestamp_utc,
            hash=h,
        )

    def initialize(self, broker_equity: float) -> None:
        """Initialize the tracker with current broker equity.

        Call this once at startup. The tracker will:
        1. Try to load existing baseline from disk
        2. If baseline exists for today → use it (survives restart)
        3. If no baseline or different day → create new baseline
        """
        today = self._today_str()
        loaded = self._load_baseline()

        if loaded and loaded.date_str == today:
            # Same day — use existing baseline (survives restart)
            self._baseline = loaded
        elif loaded is None and self._baseline_file.exists():
            # Fail closed: a baseline file that exists but cannot be loaded
            # (corrupt JSON, missing fields, hash mismatch) must NEVER silently
            # reset to current equity — that would silently disable the daily
            # loss limit for the rest of the trading day. is_daily_loss_breached
            # stays True (blocking) until an operator explicitly re-baselines
            # via force_reset(). Mirrors RiskEnforcer's CORRUPTED recovery
            # state (P1-B).
            self._corrupted = True
            self._baseline = None
        else:
            # New day or no baseline — create from current equity
            self._baseline = self._make_baseline(today, broker_equity)
            self._save_baseline(self._baseline)

        self._current_equity = broker_equity

    def update(self, equity: float) -> None:
        """Update with current equity. Handles day rollover."""
        self._current_equity = equity
        if self._corrupted:
            # Stay fail-closed: never overwrite an untrusted baseline file.
            # Operator must call force_reset() to re-baseline deliberately.
            return
        today = self._today_str()

        # Check for day rollover
        if self._baseline is None or self._baseline.date_str != today:
            # New day — create new baseline
            self._baseline = self._make_baseline(today, equity)
            self._save_baseline(self._baseline)

    @property
    def baseline_equity(self) -> float:
        """The equity at the start of the current trading day."""
        if self._baseline is None:
            return self._current_equity  # Fail closed: no baseline = current
        return self._baseline.equity

    @property
    def daily_loss(self) -> float:
        """Current daily loss (positive = loss, 0 = no loss)."""
        loss = self.baseline_equity - self._current_equity
        return max(0.0, loss)  # Only track losses, not profits

    @property
    def daily_pnl(self) -> float:
        """Current daily P&L (negative = loss)."""
        return self._current_equity - self.baseline_equity

    @property
    def baseline_trusted(self) -> bool:
        """Whether the persisted baseline was loaded and verified.

        False means the baseline file existed but was corrupted/unreadable:
        the daily-loss limit cannot be enforced against a known baseline, so
        the tracker fails closed (is_daily_loss_breached is True) until an
        operator reviews and calls force_reset().
        """
        return not self._corrupted

    @property
    def is_daily_loss_breached(self) -> bool:
        """Check if daily loss exceeds the limit.

        Fail closed: an untrusted (corrupted) baseline blocks trading even
        though no loss amount can be computed — trading without a working
        daily-loss limit is the worse outcome.
        """
        if self._corrupted:
            return True
        return self.daily_loss > self._max_daily_loss

    @property
    def remaining_daily_loss_budget(self) -> float:
        """How much more can be lost before breach."""
        return max(0.0, self._max_daily_loss - self.daily_loss)

    @property
    def baseline_date(self) -> str:
        """The date string of the current baseline."""
        if self._baseline is None:
            return ""
        return self._baseline.date_str

    def force_reset(self, equity: float) -> None:
        """Force a new baseline (e.g., after reconnect).

        This is the ONLY way to clear a corrupted-baseline fail-closed state:
        re-baselining is an explicit operator decision, never an automatic
        side effect of a restart.
        """
        today = self._today_str()
        self._baseline = self._make_baseline(today, equity)
        self._save_baseline(self._baseline)
        self._current_equity = equity
        self._corrupted = False

    def to_dict(self) -> Dict[str, Any]:
        """Export current state for diagnostics."""
        return {
            "baseline_date": self.baseline_date,
            "baseline_equity": self.baseline_equity,
            "current_equity": self._current_equity,
            "daily_loss": self.daily_loss,
            "daily_pnl": self.daily_pnl,
            "max_daily_loss": self._max_daily_loss,
            "is_breached": self.is_daily_loss_breached,
            "baseline_trusted": self.baseline_trusted,
            "remaining_budget": self.remaining_daily_loss_budget,
        }
